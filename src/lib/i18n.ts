export const DICT = { EN, HI };
export type Key = keyof typeof EN;
export function tr(
  lang: Lang,
  key: Key,
  vars: Record<string, string | number> = {},
): string {
  return (DICT[lang]?.[key] ?? EN[key]).replace(/\{(\w+)\}/g, (_, k) =>
    String(vars[k] ?? ""),
  );
}
